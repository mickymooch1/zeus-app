@app.post("/auth/register")
@limiter.limit("10/minute")
async def register(request: Request, body: RegisterRequest):
    if not body.tc_accepted:
        raise HTTPException(status_code=400, detail="You must accept the Terms & Conditions")

    if not body.email or "@" not in body.email:
        raise HTTPException(status_code=400, detail="Invalid email address")

    if len(body.password) < 8:
        raise HTTPException(status_code=400, detail="Password must be at least 8 characters")

    try:
        db_path = db.get_db_path()
    except Exception as exc:
        log.exception("register: failed to get DB path")
        raise HTTPException(status_code=500, detail=f"Database unavailable: {exc}")

    ip = (request.headers.get("x-forwarded-for") or "").split(",")[0].strip() or (request.client.host if request.client else "unknown")
    if not db.check_and_record_registration_attempt(db_path, ip):
        raise HTTPException(
            status_code=429,
            detail="Too many accounts created from this device. Please try again tomorrow.",
        )

    existing = db.get_user_by_email(db_path, body.email)
    if existing:
        raise HTTPException(status_code=409, detail="An account with that email already exists")

    try:
        password_hash = auth.hash_password(body.password)
    except Exception as exc:
        log.exception("register: password hashing failed")
        raise HTTPException(status_code=500, detail=f"Password hashing failed: {exc}")

    tc_accepted_at = datetime.now(timezone.utc).isoformat()

    try:
        user = db.create_user(
            db_path,
            email=body.email,
            password_hash=password_hash,
            name=body.name.strip(),
            tc_accepted_at=tc_accepted_at,
        )
    except Exception as exc:
        log.exception("register: create_user failed")
        raise HTTPException(status_code=500, detail=f"Could not create account: {exc}")

    # Create Stripe customer if Stripe is enabled
    if billing.stripe_enabled():
        customer_id = billing.create_stripe_customer(user)
        if customer_id:
            db.update_user(db_path, user["id"], stripe_customer_id=customer_id)
            user = db.get_user_by_id(db_path, user["id"])

    token = auth.create_token(user["id"], user["email"], is_admin=bool(user.get("is_admin", 0)))
    safe_user = {k: v for k, v in user.items() if k != "password_hash"}

    # Send verification email
    _send_verification_email(user, body.app)

    return {"token": token, "user": safe_user}


