@app.post("/api/songs/variants/{variant_id}/upload-youtube")
async def upload_to_youtube(
    variant_id: int,
    body: YouTubeUploadRequest,
    request: Request,
    current_user: dict = Depends(auth.get_current_user),
):
    """Upload a completed song variant to the user's YouTube channel."""
    # Site detection: Zeus Beats users get a zeusbeats.com-branded description.
    # Prefer Origin (set by browsers on CORS requests), fall back to Referer
    # then Host so server-to-server callers still get a sane default.
    _site_source = (
        request.headers.get("origin", "")
        or request.headers.get("referer", "")
        or request.headers.get("host", "")
    ).lower()
    site = "beats" if "zeusbeats" in _site_source else "web"

    is_admin = bool(current_user.get("is_admin", 0))
    plan = current_user.get("subscription_plan")
    if not is_admin and plan not in _YOUTUBE_PLANS:
        raise HTTPException(status_code=403, detail="YouTube upload requires Agency plan or above")

    if not current_user.get("youtube_refresh_token"):
        raise HTTPException(status_code=400, detail="YouTube not connected — visit /api/youtube/auth first")

    if body.privacy not in ("public", "unlisted", "private"):
        raise HTTPException(status_code=400, detail="privacy must be public, unlisted, or private")

    db_path = db.get_db_path()
    variant = db.get_song_variant_by_id(db_path, variant_id)
    if not variant or variant["user_id"] != current_user["id"]:
        raise HTTPException(status_code=404, detail="Song not found")
    if variant["status"] != "complete":
        raise HTTPException(status_code=400, detail="Song is not ready yet")

    title = body.title or db.get_lyric_title(db_path, variant["lyric_id"]) or f"Song #{variant_id}"

    # Prefer the D-ID avatar video (full motion) over the still-image mux when available.
    prebuilt_mp4 = None
    if variant.get("video_url"):
        prebuilt_mp4 = pathlib.Path("/data/videos") / f"{variant_id}.mp4"
        if not prebuilt_mp4.exists():
            prebuilt_mp4 = None  # file missing — fall back to FFmpeg mux

    try:
        youtube_url = youtube_uploader.upload_song_to_youtube(
            variant=variant,
            user=current_user,
            privacy=body.privacy,
            title=title,
            prebuilt_mp4=prebuilt_mp4,
            site=site,
        )
    except ValueError as exc:
        exc_str = str(exc)
        if "invalid_grant" in exc_str.lower():
            log.warning("upload_to_youtube: invalid_grant — clearing expired YT token for user %s", current_user["id"])
            db.update_user(db_path, current_user["id"], youtube_refresh_token=None)
            raise HTTPException(status_code=401, detail="youtube_reconnect_required")
        if "exceeded" in exc_str.lower() and "video" in exc_str.lower():
            raise HTTPException(
                status_code=400,
                detail=(
                    "YouTube daily upload limit reached. Please try again tomorrow or verify "
                    "your YouTube channel at youtube.com/verify to increase your limit."
                ),
            )
        raise HTTPException(status_code=400, detail=exc_str)
    except subprocess.CalledProcessError as exc:
        log.error("upload_to_youtube: ffmpeg failed: %s", exc.stderr)
        raise HTTPException(status_code=500, detail="Audio processing failed")
    except Exception as exc:
        exc_str = str(exc)
        if "invalid_grant" in exc_str.lower():
            log.warning("upload_to_youtube: invalid_grant in exception — clearing token for user %s", current_user["id"])
            db.update_user(db_path, current_user["id"], youtube_refresh_token=None)
            raise HTTPException(status_code=401, detail="youtube_reconnect_required")
        log.exception("upload_to_youtube: unexpected error")
        raise HTTPException(status_code=500, detail="Upload failed — please try again")

    db.update_song_variant(db_path, variant_id, youtube_url=youtube_url)
    return {"youtube_url": youtube_url}


