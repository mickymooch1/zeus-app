def slugify(text: str) -> str:
    text = text.lower()
    text = _re.sub(r'[^a-z0-9\s-]', '', text)
    text = _re.sub(r'[\s-]+', '-', text).strip('-')
    return text[:60]


def generate_pdf(text: str, title: str) -> bytes:
    pdf = FPDF()
    pdf.add_page()
    pdf.set_margins(20, 20, 20)

    # Title
    pdf.set_font("Helvetica", style="B", size=18)
    pdf.cell(0, 12, title, align="C", new_x="LMARGIN", new_y="NEXT")

    # Horizontal rule
    pdf.set_draw_color(180, 180, 180)
    pdf.set_line_width(0.5)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(4)

    # Body
    pdf.set_font("Helvetica", size=11)
    pdf.set_text_color(30, 30, 30)
    for para in text.split("\n\n"):
        para = para.strip()
        if not para:
            continue
        pdf.multi_cell(0, 6, para)
        pdf.ln(4)

    # Footer
    pdf.set_y(-15)
    pdf.set_font("Helvetica", size=8)
    pdf.set_text_color(150, 150, 150)
    pdf.cell(0, 5, "Generated by Zeus \u00b7 zeusaidesign.com", align="C")

    return bytes(pdf.output())


def generate_docx(text: str, title: str) -> bytes:
    doc = DocxDocument()

    # Title as Heading 1
    doc.add_heading(title, level=1)

    # Body — double-newline = paragraph, single-newline = line break within paragraph
    for para_text in text.split("\n\n"):
        para_text = para_text.strip()
        if not para_text:
            continue
        lines = para_text.split("\n")
        para = doc.add_paragraph(lines[0])
        for line in lines[1:]:
            # Word line break must be in its own run before the text run
            br_run = para.add_run()
            br = OxmlElement("w:br")
            br_run._r.append(br)
            para.add_run(line)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _send_email(to: str, subject: str, body: str) -> None:
    """Send a plain-text email via Gmail SMTP. Logs time taken. Call from a background thread."""
    smtp_email = os.environ.get("SMTP_EMAIL", "").strip()
    smtp_password = os.environ.get("SMTP_PASSWORD", "").strip()
    if not smtp_email or not smtp_password:
        log.warning("_send_email: SMTP_EMAIL/SMTP_PASSWORD not set — skipping")
        return

    msg = MIMEMultipart()
    msg["From"] = smtp_email
    msg["To"] = to
    msg["Subject"] = subject
    msg.attach(MIMEText(body, "plain"))

    t0 = time.monotonic()
    try:
        with smtplib.SMTP("smtp.gmail.com", 587) as server:
            server.settimeout(10)
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(smtp_email, smtp_password)
            server.sendmail(smtp_email, [to], msg.as_string())
        log.info("_send_email: sent to %s in %.2fs", to, time.monotonic() - t0)
    except smtplib.SMTPAuthenticationError:
        log.exception("_send_email: Gmail auth failed (%.2fs) — SMTP_PASSWORD must be an App Password", time.monotonic() - t0)
    except Exception:
        log.exception("_send_email: failed to send to %s after %.2fs", to, time.monotonic() - t0)


def _send_email_async(to: str, subject: str, body: str) -> None:
    """Fire-and-forget: run _send_email in a daemon thread so the caller returns immediately."""
    threading.Thread(target=_send_email, args=(to, subject, body), daemon=True).start()


