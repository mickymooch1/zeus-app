def slugify(text: str) -> str:
    text = text.lower()
    text = _re.sub(r'[^a-z0-9\s-]', '', text)
    text = _re.sub(r'[\s-]+', '-', text).strip('-')
    return text[:60]


def generate_pdf(text: str, title: str) -> bytes:
    pdf = FPDF()
    pdf.add_page()
    pdf.set_margins(20, 20, 20)

    # Title
    pdf.set_font("Helvetica", style="B", size=18)
    pdf.cell(0, 12, title, align="C", new_x="LMARGIN", new_y="NEXT")

    # Horizontal rule
    pdf.set_draw_color(180, 180, 180)
    pdf.set_line_width(0.5)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(4)

    # Body
    pdf.set_font("Helvetica", size=11)
    pdf.set_text_color(30, 30, 30)
    for para in text.split("\n\n"):
        para = para.strip()
        if not para:
            continue
        pdf.multi_cell(0, 6, para)
        pdf.ln(4)

    # Footer
    pdf.set_y(-15)
    pdf.set_font("Helvetica", size=8)
    pdf.set_text_color(150, 150, 150)
    pdf.cell(0, 5, "Generated by Zeus \u00b7 zeusaidesign.com", align="C")

    return bytes(pdf.output())


def generate_docx(text: str, title: str) -> bytes:
    doc = DocxDocument()

    # Title as Heading 1
    doc.add_heading(title, level=1)

    # Body — double-newline = paragraph, single-newline = line break within paragraph
    for para_text in text.split("\n\n"):
        para_text = para_text.strip()
        if not para_text:
            continue
        lines = para_text.split("\n")
        para = doc.add_paragraph(lines[0])
        for line in lines[1:]:
            # Word line break must be in its own run before the text run
            br_run = para.add_run()
            br = OxmlElement("w:br")
            br_run._r.append(br)
            para.add_run(line)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _send_via_resend(to: str, subject: str, html: str, text: str, api_key: str) -> bool:
    """Send via Resend REST API. Returns True on success."""
    t0 = time.monotonic()
    try:
        resp = httpx.post(
            "https://api.resend.com/emails",
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            json={
                "from": "Zeus Beats <hello@zeusbeats.com>",
                "to": [to],
                "subject": subject,
                "html": html,
                "text": text,
                "reply_to": "hello@zeusbeats.com",
                "headers": {
                    "X-Entity-Ref-ID": str(uuid.uuid4()),
                },
                "tags": [{"name": "category", "value": "transactional"}],
            },
            timeout=15,
        )
        if resp.status_code < 300:
            log.info("_send_email[resend]: OK to=%s id=%s elapsed=%.2fs",
                     to, resp.json().get("id", "?"), time.monotonic() - t0)
            return True
        log.error("_send_email[resend]: FAIL to=%s status=%d body=%r elapsed=%.2fs",
                  to, resp.status_code, resp.text, time.monotonic() - t0)
        return False
    except Exception:
        log.exception("_send_email[resend]: exception to=%s elapsed=%.2fs", to, time.monotonic() - t0)
        return False


def _send_via_smtp(to: str, subject: str, html: str, text: str) -> bool:
    """Send via Gmail SMTP with one retry after 5 s. Returns True on success."""
    smtp_email = os.environ.get("SMTP_EMAIL", "").strip()
    smtp_password = os.environ.get("SMTP_PASSWORD", "").strip()
    if not smtp_email or not smtp_password:
        log.warning("_send_email[smtp]: SMTP_EMAIL/SMTP_PASSWORD not set — skipping")
        return False

    msg = MIMEMultipart("alternative")
    msg["From"] = f"Zeus Beats <{smtp_email}>"
    msg["To"] = to
    msg["Reply-To"] = "hello@zeusbeats.com"
    msg["Subject"] = subject
    msg["X-Mailer"] = "Zeus Platform"
    msg.attach(MIMEText(text, "plain"))
    msg.attach(MIMEText(html, "html"))

    def _attempt(attempt: int) -> bool:
        t0 = time.monotonic()
        try:
            with smtplib.SMTP("smtp.gmail.com", 587) as server:
                server.settimeout(15)
                server.ehlo()
                server.starttls()
                server.ehlo()
                server.login(smtp_email, smtp_password)
                server.sendmail(smtp_email, [to], msg.as_string())
            log.info("_send_email[smtp]: OK to=%s attempt=%d elapsed=%.2fs", to, attempt, time.monotonic() - t0)
            return True
        except smtplib.SMTPAuthenticationError:
            log.error("_send_email[smtp]: auth FAILED attempt=%d elapsed=%.2fs — "
                      "check Gmail App Password is still valid", attempt, time.monotonic() - t0)
            return False
        except Exception:
            log.exception("_send_email[smtp]: exception to=%s attempt=%d elapsed=%.2fs",
                          to, attempt, time.monotonic() - t0)
            return False

    if _attempt(1):
        return True
    log.warning("_send_email[smtp]: retrying in 5s for %s", to)
    time.sleep(5)
    return _attempt(2)


def _send_email(to: str, subject: str, html: str, text: str) -> bool:
    """Send email via Resend (if RESEND_API_KEY set) or Gmail SMTP fallback.
    Returns True on success. Call from a background thread."""
    resend_key = os.environ.get("RESEND_API_KEY", "").strip()
    if resend_key:
        return _send_via_resend(to, subject, html, text, resend_key)
    return _send_via_smtp(to, subject, html, text)


def _send_email_async(to: str, subject: str, html: str, text: str) -> None:
    """Fire-and-forget: run _send_email in a daemon thread so the caller returns immediately."""
    threading.Thread(target=_send_email, args=(to, subject, html, text), daemon=True).start()


